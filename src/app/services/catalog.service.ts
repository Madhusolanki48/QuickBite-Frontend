  readonly categoriesSignal = signal(this.categories);
  readonly restaurantsSignal = signal(this.readRestaurants());
  readonly menuItemsSignal = signal(this.readMenuItems());

  constructor() {
    this.sync.on('catalog', () => {
      this.restaurantsSignal.set(this.readRestaurants());
      this.menuItemsSignal.set(this.readMenuItems());
    });
    this.refreshFromBackend();
  }

  private refreshFromBackend(): void {
    this.http.get<BackendRestaurantResponse[]>(`${this.baseUrl}/restaurants`).subscribe({
      next: (restaurants) => {
        const mappedRestaurants = restaurants.map((restaurant) => restaurantToFrontend(restaurant));
        const mappedMenus = restaurants.flatMap((restaurant) =>
          (restaurant.menuItems ?? []).map((item) =>
            menuToFrontend(
              slugify(restaurant.name),
              restaurant.name,
              restaurant.id,
              item as BackendMenuItemResponse,
            ),
          ),
        );

        const localRestaurants = this.readRestaurants();
        const combinedRestaurants = mappedRestaurants.length
          ? [
              ...mappedRestaurants,
              ...localRestaurants.filter(
                (lr) => !mappedRestaurants.some((br) => br.id === lr.id),
              ),
            ]
          : localRestaurants;

        const localMenus = this.readMenuItems();
        const combinedMenus = mappedMenus.length
          ? [
              ...mappedMenus,
              ...localMenus.filter(
                (lm) =>
                  !mappedMenus.some(
                    (bm) =>
                      bm.id === lm.id ||
                      bm.name.toLowerCase().trim() === lm.name.toLowerCase().trim(),
                  ),
              ),
            ]
          : localMenus;

        this.restaurantsSignal.set(combinedRestaurants);
        this.menuItemsSignal.set(combinedMenus);
      },
      error: () => {
        this.restaurantsSignal.set(this.readRestaurants());
        this.menuItemsSignal.set(this.readMenuItems());
      },
    });
  }

  categoryList() {
    return this.categoriesSignal();
  }

  restaurantList() {
    return this.restaurantsSignal();
  }

  restaurantById(id: string) {
    return this.restaurantsSignal().find((restaurant) => restaurant.id === id);
  }

  menuForRestaurant(id: string) {
    return this.menuItemsSignal().filter((item) => item.restaurantId === id);
  }

  matchesDishCategory(item: MenuItem, categoryId: string): boolean {
    if (!categoryId || categoryId === 'all') {
      return true;
    }
    const cat = categoryId.toLowerCase().trim();
    const itemCat = (item.category || '').toLowerCase().trim();
    const text = `${item.name} ${item.description || ''}`.toLowerCase();

    if (cat === 'burger' || cat === 'burgers') {
      return text.includes('burger');
    }
    if (cat === 'pizza' || cat === 'pizzas') {
      return text.includes('pizza');
    }
    if (cat === 'pasta' || cat === 'pastas') {
      return text.includes('pasta') || text.includes('penne') || text.includes('alfredo') || text.includes('arrabbiata');
    }
    if (cat === 'pizza-pasta' || cat === 'pizza & pasta') {
      return itemCat === 'pizza & pasta' || text.includes('pizza') || text.includes('pasta') || text.includes('penne') || text.includes('alfredo');
    }
    if (cat === 'quick-bites' || cat === 'quick bites' || cat === 'sandwiches' || cat === 'sandwich') {
      return itemCat === 'quick bites' || text.includes('sandwich') || text.includes('wrap');
    }
    if (cat === 'indian' || cat === 'biryani' || cat === 'south indian') {
      return itemCat === 'indian';
    }
    if (cat === 'asian' || cat === 'sushi' || cat === 'chinese' || cat === 'noodles' || cat === 'momos') {
      return itemCat === 'asian';
    }
    if (cat === 'sides') {
      return itemCat === 'sides';
    }
    if (cat === 'healthy') {
      return itemCat === 'healthy';
    }
    if (cat === 'desserts' || cat === 'dessert') {
      return itemCat === 'desserts';
    }
    if (cat === 'drinks' || cat === 'drink') {
      return itemCat === 'drinks';
    }

    return itemCat === cat || itemCat.includes(cat);
  }

  restaurantsForCategory(categoryId: string): Restaurant[] {
    if (!categoryId || categoryId === 'all') {
      return this.restaurantsSignal();
    }
    const allItems = this.menuItemsSignal();
    const matchingRestIds = new Set<string>();
    for (const item of allItems) {
      if (this.matchesDishCategory(item, categoryId)) {
        matchingRestIds.add(item.restaurantId);
      }
    }
    return this.restaurantsSignal().filter((r) => matchingRestIds.has(r.id));
  }

